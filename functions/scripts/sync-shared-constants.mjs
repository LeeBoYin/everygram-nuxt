// 把根目錄 utils/constants 的共用常數複製到 functions/src/shared。
// functions 是獨立的 TS package，讀不到根目錄的 utils/，所以 build 前先同步。
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = resolve(root, 'functions/src/shared');

// 原檔使用根目錄的全域型別（types/types.d.ts），functions 看不到，在這裡補上。
const FILES = [
    {
        name: 'gear-brands.ts',
        typeHeader: `type BrandData = { name: string; originalName?: string };\n`,
    },
    {
        name: 'gear-categories.ts',
        typeHeader: `type CategoryData = { icon: string; color: string };
type GearCategory =
    | 'accessories'
    | 'packs'
    | 'clothing'
    | 'cooking'
    | 'electronics'
    | 'photography'
    | 'hydration'
    | 'shelter'
    | 'sleeping'
    | 'tools'
    | 'others';\n`,
    },
];

mkdirSync(outDir, { recursive: true });
for (const { name, typeHeader } of FILES) {
    const src = readFileSync(resolve(root, 'utils/constants', name), 'utf8');
    const banner = `// AUTO-GENERATED by functions/scripts/sync-shared-constants.mjs from utils/constants/${name}.\n// DO NOT EDIT. Run \`npm run sync-shared\` in functions/ to regenerate.\n\n`;
    writeFileSync(resolve(outDir, name), `${banner}${typeHeader}\n${src}`);
    console.log(`synced ${name}`);
}
