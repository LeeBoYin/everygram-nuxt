// 把根目錄 utils/constants 的共用常數複製到 functions/src/shared。
// functions 是獨立的 TS package，讀不到根目錄的 utils/，所以 build 前先同步。
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = resolve(root, 'functions/src/shared');

const FILES = ['gear-brands.ts', 'gear-categories.ts'];

mkdirSync(outDir, { recursive: true });
for (const name of FILES) {
    const src = readFileSync(resolve(root, 'utils/constants', name), 'utf8');
    const banner = `// AUTO-GENERATED by functions/scripts/sync-shared-constants.mjs from utils/constants/${name}.\n// DO NOT EDIT. Run \`npm run sync-shared\` in functions/ to regenerate.\n\n`;
    writeFileSync(resolve(outDir, name), `${banner}${src}`);
    console.log(`synced ${name}`);
}
